DIRECTOR_HISTORY_BLOCK = """【我此前的往来】
我回看的是过去的往来，不是本轮新收到的消息。我保留各自的说话人、时间和来源；旧提问不意味着现在仍在等我回答，旧计划也不证明已经执行。
我可以因相关旧事想到对方、接续话题或自然问候；是否联系取决于此刻的处境、仍有效的约定和自己的意愿。没有新进展也不妨碍普通往来。
我不把旧情绪、推测或回复措辞自动沿用到现在，不为延续话题编造新事件。
【往来记录】
{lines}
"""


def director_history_block(lines: str) -> str:
    if not (lines or "").strip():
        return ""
    return DIRECTOR_HISTORY_BLOCK.replace("{lines}", lines.strip())


def director_phase_block(phase: str) -> str:
    if phase == "advance":
        return DIRECTOR_ADVANCE_BLOCK + "\n\n" + DIRECTOR_AUDIENCE_BLOCK
    return ""


